import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const mode = process.argv[2];

if (mode !== 'dev' && mode !== 'local') {
  console.error('Usage: node scripts/set-api-mode.mjs <dev|local>');
  process.exit(1);
}

const repoRoot = join(fileURLToPath(new URL('.', import.meta.url)), '..');
const target = join(repoRoot, 'src/app/api-runtime.config.ts');

const content = `// Auto-generated by scripts/set-api-mode.mjs\n\nexport const API_CLIENT_MODE: 'dev' | 'local' = '${mode}';\n`;

await writeFile(target, content, 'utf8');
